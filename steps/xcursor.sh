#!/bin/bash
# steps/xcursor.sh — system-wide mouse cursor theme and size
#
# The panel is 2560x1600 on 288x180 mm (~225 dpi) while X reports 96 dpi, so
# everything drawn at "1 px = 1/96 inch" appears at ~43% of its physical size.
# The cursor was worse than that: dwm and st asked the server for cursorfont
# glyphs with XCreateFontCursor, and those are fixed-size bitmaps — XC_left_ptr
# measures 9x16 px with XFixesGetCursorImage, i.e. a tiny arrow that no setting
# could enlarge. Both now load their cursor through libXcursor
# (steps/suckless-dwm.sh, steps/suckless-st.sh), so this size applies to every
# cursor on screen: root window, bar, terminals, GTK, Chrome, Qt.
#
# Single source of truth: dotfiles/xcursor/xcursor.conf. This step installs it
# and generates the files that consumers read:
#   /etc/xcursor.conf            the values themselves (KEY=VALUE)
#   /etc/X11/xcursor-resources   Xcursor.theme/size, merged into the root
#                                resource database by dwm-start (xrdb). Every
#                                libXcursor client reads it, including clients
#                                started outside dwm-start.
#   /etc/profile.d/xcursor.sh    XCURSOR_THEME/XCURSOR_SIZE for login shells
#   <user>/.config/gtk-3.0/settings.ini   gtk-cursor-theme-size/name
#
# Idempotent: no file is rewritten when its content already matches, and the
# GTK key sync only rewrites a settings.ini whose two cursor keys differ.

set -u

REPO_DIR="${REPO_DIR:-/root/slackware-installer-for-rs}"
LOG_FILE="${LOG_FILE:-/var/log/installer.log}"

if [ -f "$REPO_DIR/lib/common.sh" ]; then
    . "$REPO_DIR/lib/common.sh"
fi

SRC="$REPO_DIR/dotfiles/xcursor/xcursor.conf"

echo "*****************************************************"
echo "MOUSE CURSOR (theme + size, all users)"
echo "*****************************************************"

if [ ! -r "$SRC" ]; then
    echo "ERROR: $SRC not found — cannot determine the cursor size."
    exit 1
fi

# shellcheck disable=SC1090
. "$SRC"
if [ -z "${XCURSOR_THEME:-}" ] || [ -z "${XCURSOR_SIZE:-}" ]; then
    echo "ERROR: $SRC must set XCURSOR_THEME and XCURSOR_SIZE."
    exit 1
fi
echo "  theme=$XCURSOR_THEME size=${XCURSOR_SIZE}px"

# ── 1. /etc/xcursor.conf ──────────────────────────────────────────────
if [ -f /etc/xcursor.conf ] && cmp -s "$SRC" /etc/xcursor.conf; then
    echo "  /etc/xcursor.conf already up to date"
else
    install -m 644 "$SRC" /etc/xcursor.conf
    echo "  /etc/xcursor.conf installed"
fi

# ── 2. X resources (root resource database; read by libXcursor) ────────
RES_TMP=$(mktemp)
cat >"$RES_TMP" <<EOF
! Generated by steps/xcursor.sh from dotfiles/xcursor/xcursor.conf
! Do not edit: change the repo file and re-run the step.
! '!' is the X resource comment character — '#' would only parse with cpp.
Xcursor.theme: $XCURSOR_THEME
Xcursor.size: $XCURSOR_SIZE
EOF
mkdir -p /etc/X11
if [ -f /etc/X11/xcursor-resources ] && cmp -s "$RES_TMP" /etc/X11/xcursor-resources; then
    rm -f "$RES_TMP"
    echo "  /etc/X11/xcursor-resources already up to date"
else
    install -m 644 "$RES_TMP" /etc/X11/xcursor-resources
    rm -f "$RES_TMP"
    echo "  /etc/X11/xcursor-resources installed (xrdb -merge in dwm-start)"
fi

# ── 3. Login shells (/etc/profile.d) ──────────────────────────────────
PROFILE_TMP=$(mktemp)
cat >"$PROFILE_TMP" <<'EOF'
# Generated by steps/xcursor.sh — mouse cursor theme and size for every user.
# libXcursor reads these when a client creates a cursor; Xcursor.size in the
# root resource database (set by dwm-start) says the same thing, this covers
# clients started without a dwm-start session (ssh, scripts, other WMs).
if [ -r /etc/xcursor.conf ]; then
    . /etc/xcursor.conf
    export XCURSOR_THEME XCURSOR_SIZE
fi
EOF
if [ -f /etc/profile.d/xcursor.sh ] && cmp -s "$PROFILE_TMP" /etc/profile.d/xcursor.sh; then
    rm -f "$PROFILE_TMP"
    echo "  /etc/profile.d/xcursor.sh already up to date"
else
    mkdir -p /etc/profile.d
    install -m 644 "$PROFILE_TMP" /etc/profile.d/xcursor.sh
    rm -f "$PROFILE_TMP"
    echo "  /etc/profile.d/xcursor.sh installed"
fi

# ── 4. GTK (Chrome, dialogs, any GTK app) ─────────────────────────────
# GTK does not consult Xcursor.size once gtk-cursor-theme-size is present, and
# 0 means "whatever the toolkit thinks" — so the two keys are written
# explicitly in every existing user's settings.ini, and in the skeleton for
# users created later. Only those two keys are touched.
GTK_SRC="$REPO_DIR/dotfiles/gtk/settings.ini"

sync_gtk_ini() {
    ini=$1
    new=$(awk -v s="$XCURSOR_SIZE" -v t="$XCURSOR_THEME" '
        /^[ \t]*gtk-cursor-theme-size[ \t]*=/ { print "gtk-cursor-theme-size=" s; done_s = 1; next }
        /^[ \t]*gtk-cursor-theme-name[ \t]*=/ { print "gtk-cursor-theme-name=" t; done_t = 1; next }
        { print }
        END {
            if (!done_s) print "gtk-cursor-theme-size=" s
            if (!done_t) print "gtk-cursor-theme-name=" t
        }' "$ini")
    if [ "$new" = "$(cat "$ini")" ]; then
        echo "  $ini already ${XCURSOR_SIZE}px"
    else
        printf '%s\n' "$new" > "$ini"
        echo "  $ini -> ${XCURSOR_SIZE}px $XCURSOR_THEME"
    fi
}

# Human accounts only: getent lists the system accounts too (ftp and slskd
# have home directories, and writing a GTK config into a service account is
# not a cursor fix), so require uid >= 1000 AND a home under /home (root and
# /etc/skel are covered explicitly, so root and future users get it as well).
gtk_users="/root /etc/skel"
while IFS=: read -r _name _pw uid _gid _gecos home _shell; do
    case "$uid" in ''|*[!0-9]*) continue ;; esac
    [ "$uid" -ge 1000 ] && [ "$uid" -lt 65000 ] || continue
    case "$home" in /home/?*) ;; *) continue ;; esac
    [ -d "$home" ] && gtk_users="$gtk_users $home"
done <<EOF
$(getent passwd)
EOF

for base in $gtk_users; do
    [ -d "$base" ] || continue
    ini="$base/.config/gtk-3.0/settings.ini"
    if [ ! -f "$ini" ]; then
        [ -r "$GTK_SRC" ] || continue
        mkdir -p "$(dirname "$ini")"
        cp "$GTK_SRC" "$ini" && echo "  $ini created from dotfiles"
    fi
    sync_gtk_ini "$ini"
done

echo "SUCCESS: cursor is $XCURSOR_THEME at ${XCURSOR_SIZE}px for all users."
echo "  Takes effect in a new X session; the running one keeps the old"
exit 0
